"""Print a real one-step DQN Bellman-target calculation from the trained model."""
from pathlib import Path
import sys
import numpy as np
import torch
import torch.nn.functional as F

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "code"))
from routing_environment import RoutingEnvironment
from dqn_agent import DQNAgent

MODEL = ROOT / "results" / "dqn_model.pth"


def main():
    if not MODEL.exists():
        print("No trained six-router model found. Train it first: python member2_ai/train.py")
        raise SystemExit(1)
    torch.manual_seed(7)
    env = RoutingEnvironment(seed=7)
    state = env.reset(source="R1", destination="R5")
    agent = DQNAgent(env.state_size, env.action_size)
    agent.load(str(MODEL))
    agent.epsilon = 0.0
    action = agent.choose_action(state, env.valid_actions(), training=False)
    next_state, reward, done, info = env.step(action)

    s = torch.as_tensor(np.asarray(state, dtype=np.float32), device=agent.device).unsqueeze(0)
    ns = torch.as_tensor(np.asarray(next_state, dtype=np.float32), device=agent.device).unsqueeze(0)
    with torch.no_grad():
        q_sa = float(agent.model(s)[0, action].item())
        next_actions = [] if done else env.valid_actions()
        max_next_q = float(agent.target_model(ns)[0, next_actions].max().item()) if next_actions else 0.0
        target = float(reward + agent.gamma * max_next_q * (0.0 if done else 1.0))
        td_error = target - q_sa
        huber_loss = float(F.smooth_l1_loss(torch.tensor(q_sa), torch.tensor(target)).item())

    print("One-step DQN calculation (actual values from this run)")
    print(f"Current router: {env.id_to_router[0]}")
    print(f"Chosen next hop: {env.id_to_router[action]}")
    print(f"Immediate reward r: {reward:.6f}")
    print(f"Discount factor gamma: {agent.gamma:.4f}")
    print(f"Current Q(s,a): {q_sa:.6f}")
    print(f"Max next Q(s',a'): {max_next_q:.6f}")
    print(f"Bellman target y = r + gamma * maxQ (unless terminal): {target:.6f}")
    print(f"TD error = target - Q(s,a): {td_error:.6f}")
    print(f"Smooth-L1/Huber loss for this sample: {huber_loss:.6f}")
    print(f"Done: {done}; route info: {info}")
    print("These values are generated by the saved model; they can change after retraining.")


if __name__ == "__main__":
    main()
